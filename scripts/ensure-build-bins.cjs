#!/usr/bin/env node
/**
 * Installs self-healing wrappers for the build toolchain.
 *
 * Why this exists: a deploy container's node_modules snapshot/cache was
 * left in a state where bare `tsc` resolved to the registry troll package
 * ("This is not the tsc command you are looking for") — via a stale .bin
 * link, a fake alias package, or even a fake `typescript` directory.
 *
 * This hook (package.json "postinstall") writes node_modules/.bin/{tsc,
 * tsserver,vite} as small POSIX wrappers that, at execution time:
 *   1. behaviorally verify the real tool (run it, expect known output),
 *   2. if broken/absent, reinstall it fresh (npm i --no-save),
 *   3. then exec the real binary.
 * A fake package that merely *claims* to be TypeScript cannot pass step 1.
 *
 * Never throws — a failed repair must not break installs; it only warns.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const binDir = path.join(root, "node_modules", ".bin");

const TOOLS = [
  { link: "tsc", pkg: "typescript", bin: "bin/tsc", probe: "--version", expect: "Version" },
  { link: "tsserver", pkg: "typescript", bin: "bin/tsserver", probe: "--version", expect: "Version" },
  { link: "vite", pkg: "vite", bin: "bin/vite.js", probe: "--version", expect: "vite/" },
];

function wrapperScript(tool) {
  // POSIX sh. Resolves the real binary relative to this wrapper's location
  // (node_modules/.bin), verifies it behaviorally, self-repairs if needed.
  return `#!/bin/sh
# Auto-generated by scripts/ensure-build-bins.cjs — self-healing tool wrapper.
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REAL="$DIR/../${tool.pkg}/${tool.bin}"
if node "$REAL" ${tool.probe} 2>/dev/null | grep -q "${tool.expect}"; then
  exec node "$REAL" "$@"
fi
echo "[self-heal] real ${tool.pkg} missing or fake; reinstalling..." >&2
if command -v npm >/dev/null 2>&1; then
  (cd "$DIR/.." && npm install --no-save --no-audit --no-fund ${tool.pkg} >/dev/null 2>&1) || true
fi
exec node "$REAL" "$@"
`;
}

try {
  fs.mkdirSync(binDir, { recursive: true });
  for (const tool of TOOLS) {
    const abs = path.join(root, "node_modules", tool.pkg, tool.bin);
    if (!fs.existsSync(abs)) {
      console.warn(`[ensure-build-bins] ${tool.pkg} not installed yet; skipping .bin/${tool.link}`);
      continue;
    }
    const linkPath = path.join(binDir, tool.link);
    try {
      fs.rmSync(linkPath, { force: true });
    } catch {
      /* best-effort */
    }
    try {
      fs.writeFileSync(linkPath, wrapperScript(tool), { mode: 0o755 });
      fs.chmodSync(linkPath, 0o755);
    } catch (err) {
      console.warn(`[ensure-build-bins] could not write .bin/${tool.link}: ${err.message}`);
    }
  }
  console.log("[ensure-build-bins] self-healing wrappers installed for tsc/tsserver/vite");
} catch (err) {
  console.warn(`[ensure-build-bins] skipped: ${err.message}`);
}
